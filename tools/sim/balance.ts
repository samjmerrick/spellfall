// pnpm sim:balance [n=200] [--out docs/balance.md]
// Spellfall balance report (spec V8): mono-faction decks (every collectible card of the faction once), every
// ordered pairing including mirrors, n matches each, Normal vs Normal, seeds in a fixed order so the report is
// reproducible. Exits 1 if anything is out of target without a reason in tools/sim/balance-exceptions.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { FACTIONS, getCard } from '../../src/rules';
import { balanceRun, summarise } from './balance-core';

export const TARGETS = {
  faction: [0.45, 0.55],
  firstPlayer: [0.47, 0.53],
  cardMax: 0.6,
  /** Cards played fewer times than this are not judged. */
  cardMinPlays: 100,
  medianTurns: [14, 22],
} as const;

const args = process.argv.slice(2);
const outAt = args.indexOf('--out');
const out = outAt >= 0 ? args[outAt + 1]! : 'docs/balance.md';
const n = Number(args.find((a, i) => /^\d+$/.test(a) && args[i - 1] !== '--out') ?? 200);
const exceptions = JSON.parse(readFileSync('tools/sim/balance-exceptions.json', 'utf8')) as {
  factions: Record<string, string>;
  cards: Record<string, string>;
  firstPlayer?: string;
  medianTurns?: string;
};

const start = performance.now();
const s = summarise(balanceRun(n));
const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const problems: string[] = [];
const lines: string[] = [
  '# Spellfall balance report',
  '',
  `Generated by \`pnpm sim:balance ${n}\`: ${s.matches} Normal-vs-Normal matches, ${n} per ordered faction pairing ` +
    '(mirrors included), mono-faction decks of every collectible card of the faction. A draw counts as a loss. ' +
    'Seeds run in a fixed order, so the report is reproducible.',
  '',
  '## Match shape',
  '',
  '| Measure | Value | Target |',
  '|---|---|---|',
];
const flag = (ok: boolean, reason?: string) =>
  ok ? '' : reason ? ` (exception: ${reason})` : ' **out of target**';
const firstOk = s.firstPlayer >= TARGETS.firstPlayer[0] && s.firstPlayer <= TARGETS.firstPlayer[1];
const turnsOk = s.medianTurns >= TARGETS.medianTurns[0] && s.medianTurns <= TARGETS.medianTurns[1];
lines.push(`| First player wins | ${pct(s.firstPlayer)}${flag(firstOk, exceptions.firstPlayer)} | 47–53% |`);
lines.push(
  `| Median match length | ${s.medianTurns} turns${flag(turnsOk, exceptions.medianTurns)} | 14–22 turns |`,
);
lines.push(`| Draws | ${pct(s.draws)} | — |`);
if (!firstOk && !exceptions.firstPlayer) problems.push(`first player ${pct(s.firstPlayer)}`);
if (!turnsOk && !exceptions.medianTurns) problems.push(`median turns ${s.medianTurns}`);

lines.push('', '## Factions (non-mirror matches)', '', '| Faction | Win rate | |', '|---|---|---|');
for (const f of FACTIONS) {
  const r = s.factions[f] ?? 0;
  const ok = r >= TARGETS.faction[0] && r <= TARGETS.faction[1];
  lines.push(`| ${f} | ${pct(r)} | ${flag(ok, exceptions.factions[f]).trim()} |`);
  if (!ok && !exceptions.factions[f]) problems.push(`${f} ${pct(r)}`);
}

lines.push(
  '',
  `## Cards (win rate when played; judged from ${TARGETS.cardMinPlays} plays, target at most ${pct(TARGETS.cardMax)})`,
  '',
  '| Card | Faction | Played | Win rate when played | |',
  '|---|---|---|---|---|',
);
const cards = Object.entries(s.cards).sort((a, b) => b[1].rate - a[1].rate);
for (const [id, c] of cards) {
  const judged = c.played >= TARGETS.cardMinPlays;
  const ok = !judged || c.rate <= TARGETS.cardMax;
  const note = !judged ? 'too few plays' : flag(ok, exceptions.cards[id]).trim();
  lines.push(`| ${getCard(id).name} | ${getCard(id).faction} | ${c.played} | ${pct(c.rate)} | ${note} |`);
  if (!ok && !exceptions.cards[id]) problems.push(`${id} ${pct(c.rate)}`);
}
lines.push('');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out}: ${s.matches} matches in ${((performance.now() - start) / 1000).toFixed(0)} s`);
if (problems.length > 0) {
  console.error(`Out of target without a reason in balance-exceptions.json: ${problems.join(', ')}`);
  process.exit(1);
}
